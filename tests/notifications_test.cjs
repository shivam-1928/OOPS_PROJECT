const assert = require('node:assert/strict');
const { NotificationStore, cleanState, normalize, inbox, hasP1, dismissSwipe } = require('../frontend/notifications.js');
let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const raw = [
  '2026-11-20T10:00:00.123456 | To: E001 | Incident INC0001 has been created with priority P1.',
  '2026-11-20T11:00:00 | To: E001 | Incident INC0001 status is now IN_PROGRESS.',
  '2026-11-20T12:00:00 | To: E001 | Incident INC0001 has been resolved.'
];
const server = normalize(raw);
check(server.map(n => n.title), ['Incident reported · INC0001', 'Incident status updated · INC0001', 'Incident resolved · INC0001']);
check(server[0].incidentId, 'INC0001');
check(server[0].message, 'Incident INC0001 has been created with priority P1.');
check(normalize(raw).map(n => n.id), server.map(n => n.id));
check(new Set(normalize([raw[0], raw[0]]).map(n => n.id)).size, 2);
check(normalize(['Unstructured notification'])[0].message, 'Unstructured notification');
check(normalize(['Unstructured notification'])[0].timestamp, null);
const memory = new Map();
const storage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
const store = new NotificationStore(storage, 'E001');
check(inbox(server, store.data).map(n => n.id), [server[2].id, server[1].id, server[0].id]);
check(inbox(server, store.data).filter(n => !n.read).length, 3);
store.commit(data => data.read.push(server[2].id));
check(inbox(server, store.data)[0].read, true);
check(inbox(server, store.data).filter(n => !n.read).length, 2);
const reloaded = new NotificationStore(storage, 'E001');
check(inbox(server, reloaded.data)[0].read, true);
check(inbox(server, new NotificationStore(storage, 'T001').data).filter(n => !n.read).length, 3);
store.commit(data => data.deleted.push(server[1].id));
check(inbox(server, store.data).length, 2);
check(inbox(normalize(raw), new NotificationStore(storage, 'E001').data).some(n => n.id === server[1].id), false);
store.commit(data => { data.deleted = data.deleted.filter(id => id !== server[1].id); });
check(inbox(server, store.data).length, 3);
check(inbox(server, store.data).find(n => n.id === server[1].id).read, false);
store.commit(data => { data.order = 'oldest'; });
check(inbox(server, store.data).map(n => n.id), server.map(n => n.id));
check(new NotificationStore(storage, 'E001').data.order, 'oldest');
store.commit(data => { data.deleted = server.map(n => n.id); });
check(inbox(server, store.data), []);
const later = normalize([...raw, '2026-11-20T13:00:00 | To: E001 | Incident INC0002 has been created with priority P4.']);
check(inbox(later, store.data).length, 1);
check(inbox(later, store.data)[0].read, false);
check(hasP1([{ priority: 'P1', status: 'CLOSED' }]), true);
check(hasP1([{ priority: 'P2' }]), false);
check(hasP1([]), false);
check(dismissSwipe(-130, 5, 500), true);
check(dismissSwipe(-75, 5, 240), true);
check(dismissSwipe(-20, 0, 500), false);
check(dismissSwipe(140, 0, 500), false);
check(dismissSwipe(-110, 160, 500), false);
const otherTab = new NotificationStore(storage, 'E001');
otherTab.commit(data => data.read.push(server[0].id));
store.commit(data => data.read.push(server[1].id));
check(new NotificationStore(storage, 'E001').data.read.includes(server[0].id), true);
check(new NotificationStore(storage, 'E001').data.read.includes(server[1].id), true);
const restricted = new NotificationStore({ getItem() { throw new Error('Blocked'); } }, 'restricted');
check(restricted.persistent, false);
restricted.commit(data => data.read.push('one')); restricted.commit(data => data.read.push('two'));
check(restricted.data.read, ['one', 'two']);
const full = new NotificationStore({ getItem: () => null, setItem() { throw new Error('Quota'); } }, 'full');
full.commit(data => data.deleted.push('one')); full.commit(data => data.deleted.push('two'));
check(full.data.deleted, ['one', 'two']);
check(full.persistent, false);
check(cleanState({ read: ['one', 2, 'one'], deleted: null, demos: [{ id: 'bad', message: 'bad', timestamp: 'x' }], order: 'invalid' }), { read: ['one'], deleted: [], demos: [], order: 'latest' });
store.commit(data => data.demos.push({ id: 'demo:test', timestamp: '2026-11-20T14:00:00+05:30', message: 'Test message' }));
check(inbox([], store.data)[0].source, 'demo');
check(inbox([], store.data)[0].read, false);
console.log(`PASS: ${checks} notification parsing, persistence, sorting, badge and swipe assertions.`);
