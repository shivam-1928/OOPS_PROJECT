const assert = require('node:assert/strict');
const { groupTechnicians, eligible, warning } = require('../frontend/reassignment.js');
let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const network = { userId: 'T001', name: 'Network tech', username: 'tech1', role: 'TECHNICIAN', available: true, skills: ['EMAIL', 'NETWORK'] };
const hardware = { userId: 'T002', name: 'Hardware tech', role: 'TECHNICIAN', available: true, skills: ['SOFTWARE', 'ACCESS', 'HARDWARE'] };
const extra = { userId: 'T003', name: 'Custom tech', role: 'TECHNICIAN', available: false, skills: ['DATABASE'] };
const original = JSON.stringify([network, hardware, extra]);
check(groupTechnicians([hardware, extra, network]).map(group => group.skill), ['NETWORK', 'HARDWARE', 'DATABASE']);
check(groupTechnicians([network])[0].technicians.length, 1);
check(network.skills, ['EMAIL', 'NETWORK']);
check(groupTechnicians([{ ...extra, skills: [] }])[0].skill, 'NO_SKILLS');
check(groupTechnicians([{ role: 'EMPLOYEE', name: 'Employee' }]), []);
check(eligible(network, 'T002'), true);
check(eligible(network, 'T001'), false);
check(eligible(extra, 'T001'), false);
check(eligible({ ...network, active: false }, 'T002'), false);
check(eligible({ ...network, role: 'EMPLOYEE' }, 'T002'), false);
check(!!eligible(null, 'T002'), false);
check(warning({ category: 'NETWORK' }, hardware).includes('does not list network'), true);
check(warning({ category: 'NETWORK' }, network).includes('does not list'), false);
check(warning({ category: 'NETWORK' }, network).includes('SLA deadlines will not reset'), true);
check(JSON.stringify([network, hardware, extra]), original);
console.log(`PASS: ${checks} reassignment grouping, eligibility and warning assertions.`);
